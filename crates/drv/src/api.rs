//! The `erl_driver.h` (OTP 29.1.1) function table and which task implements each.
//!
//! A driver that references a symbol the executable does not export fails to
//! load (`dlopen(RTLD_NOW)` reports the missing symbol, as with erts). Entries
//! owned by follow-up tasks are filled in by adding the export in `exports.rs`
//! (or a new module) and moving the entry to [`Owner::Core`].

/// Task that implements an API function.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Owner {
    /// Implemented and exported by this crate.
    Core,
    /// `drv_io`: `driver_select`, timers, async jobs, time slices.
    DrvIo,
    /// `drv_lib`: queues, term output, monitors, threads, port data locks, misc.
    DrvLib,
}


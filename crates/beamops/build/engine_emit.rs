//! The printing half of `tr_gen` and `gen_te_instr` of erts/emulator/utils/beam_makeops
//! (OTP-29.1.1): the transformation engine as Rust. `goto failN` becomes `break 'failN` out of
//! nested labeled blocks, which is how Rust spells a forward jump.

use crate::makeops::*;
use crate::transform::*;
use std::collections::BTreeSet;

impl Makeops {
    /// The engine function and the atom constants it compares with.
    pub fn emit_engine(&self, programs: &Programs) -> String {
        let mut atoms: BTreeSet<String> = BTreeSet::new();
        let mut bifs: BTreeSet<String> = BTreeSet::new();
        let mut body = String::new();
        let mut label = 0usize;

        for (key, rules) in &programs.rules {
            let (name, arity) = key.split_once('/').unwrap();
            let opnum = self.gen_opnum[&(name.to_owned(), arity.parse().unwrap())];
            body.push_str(&format!("        {opnum} => {{ // {key}\n"));

            // The labels the C printer emits: before a rule when `$need_label` is set, which a
            // `skip_unless` rule clears.
            let mut emitted: Vec<usize> = Vec::new();
            let mut need_label = false;
            for (n, rule) in rules.iter().enumerate() {
                if need_label {
                    emitted.push(label + n);
                }
                need_label = !rule.steps.iter().any(|s| s.op == "skip_unless");
            }
            for l in emitted.iter().rev() {
                body.push_str(&format!("'fail{l}: {{\n"));
            }

            let mut need_label = false;
            for rule in rules {
                for line in rule_comment(&rule.comment) {
                    body.push_str(&format!("// {line}\n"));
                }
                if need_label {
                    body.push_str(&format!("}}\n// fail{label}\ninstr = Some(first);\n"));
                }
                label += 1;
                need_label = true;
                let mut ap = 0usize;
                let mut ip = 0isize;
                let mut fail_action = "return TeResult::Fail".to_owned();
                for step in &rule.steps {
                    match step.op.as_str() {
                        "next_arg" => ap += 1,
                        "next_instr" => {
                            ap = 0;
                            ip += 1;
                        }
                        "new_instr" | "commit" => ap = 0,
                        "commit_new_instr" => {
                            ap = 0;
                            ip -= 1;
                        }
                        "keep" => ip -= 1,
                        "try_me_else" => fail_action = format!("break 'fail{label}"),
                        "skip_unless" => {
                            fail_action = format!("break 'fail{label}");
                            need_label = false;
                        }
                        _ => {}
                    }
                    self.gen_te_instr(&mut body, &mut atoms, &mut bifs, ap, ip, &fail_action, step);
                }
            }
            body.push_str("        }\n");
        }

        let mut out = String::from(
            "// @generated by build/engine_emit.rs: the transformation engine of beam_makeops\n// (erts/emulator/utils/beam_makeops, tr_gen and gen_te_instr), OTP-29.1.1.\n\n",
        );
        for atom in &atoms {
            out.push_str(&format!(
                "const AM_{}: u64 = am({:?});\n",
                atom.to_uppercase(),
                atom
            ));
        }
        for bif in &bifs {
            out.push_str(&format!(
                "const {}: u16 = bif_id({:?});\n",
                bif.to_uppercase(),
                bif.strip_prefix("BIF_").unwrap()
            ));
        }
        out.push_str(
            "\n#[allow(unreachable_code, unused_labels, unused_assignments, unused_mut, unused_variables, clippy::all)]\npub(crate) fn erts_transform_engine_body(st: &mut LoaderState) -> TeResult {\n",
        );
        for n in 0..programs.te_max_vars {
            out.push_str(&format!("    let mut v{n} = BeamOpArg::default();\n"));
        }
        out.push_str(
            "    let first: OpId = st.genop.expect(\"the engine runs on a non-empty window\");\n    let mut instr: Option<OpId> = Some(first);\n    let mut keep: Option<OpId> = None;\n    let mut rest_args = RestArgs { op: first, start: 0, len: 0 };\n    let mut num_rest_args: usize = 0;\n    match st.ops.op(first).op {\n",
        );
        out.push_str(&body);
        out.push_str(
            "        _ => unreachable!(\"generic op without a transformation\"),\n    }\n}\n",
        );
        out
    }

    #[allow(clippy::too_many_arguments)]
    fn gen_te_instr(
        &self,
        out: &mut String,
        atoms: &mut BTreeSet<String>,
        bifs: &mut BTreeSet<String>,
        ap: usize,
        ip: isize,
        fail: &str,
        step: &Step,
    ) {
        let comment = &step.comment;
        let args = &step.args;
        match step.op.as_str() {
            "next_arg" | "nop" | "try_me_else" | "try_me_else_fail" => {}
            "skip_unless" => {
                let instr = &args[0];
                let count: usize = args[1].parse().unwrap();
                let fail = match fail.strip_prefix("break 'fail") {
                    Some(n) => format!("break 'fail{}", n.parse::<usize>().unwrap() + count),
                    None => fail.to_owned(),
                };
                out.push_str(&format!(
                    "// The caller guarantees a second instruction.\ndebug_assert!(instr.is_some());\nif st.ops.op(st.ops.op(instr.unwrap()).next.unwrap()).op != {instr} {{\n    {fail};\n}}\n"
                ));
            }
            "set_var" => out.push_str(&format!(
                "v{} = st.ops.op(instr.unwrap()).a({ap}); // {comment}\n",
                args[0]
            )),
            "is_bif" => {
                let number = &args[0];
                let specific = if number == "-1" {
                    String::new()
                } else {
                    bifs.insert(number.clone());
                    format!(
                        "if entry != Some({}) {{ {fail}; }}\n",
                        number.to_uppercase()
                    )
                };
                out.push_str(&format!(
                    "// Is {comment} a BIF?\n{{\nlet a = st.ops.op(instr.unwrap()).a({ap});\ndebug_assert!(a.ty == TAG_U);\nif a.ty != TAG_U {{ {fail}; }}\nlet i = a.val as usize;\ndebug_assert!(i < st.imports.len());\nif i >= st.imports.len() {{ {fail}; }}\nlet entry = st.bif_imports[i];\nif entry.is_none() {{ {fail}; }}\n{specific}}}\n"
                ));
            }
            "is_not_bif" => {
                atoms.insert("erlang".into());
                atoms.insert("apply".into());
                out.push_str(&format!(
                    "// Is {comment} not a BIF?\n{{\nlet a = st.ops.op(instr.unwrap()).a({ap});\nlet i = a.val as usize;\ndebug_assert!(a.ty == TAG_U);\nif a.ty != TAG_U {{ {fail}; }}\nif i < st.imports.len() {{\nif st.bif_imports[i].is_some() {{ {fail}; }}\nlet import = &st.imports[i];\nif import.module == AM_ERLANG && import.function == AM_APPLY && (import.arity == 2 || import.arity == 3) {{ {fail}; }}\n}}\n}}\n"
                ));
            }
            "is_eq" => {
                let val = value_expr(&args[0], atoms);
                out.push_str(&format!(
                    "if st.ops.op(instr.unwrap()).a({ap}).val != {val} {{\n    {fail};\n}}\n"
                ));
            }
            "is_func" => {
                let m = value_expr(&args[0], atoms);
                let f = value_expr(&args[1], atoms);
                let arity = &args[2];
                out.push_str(&format!(
                    "// Is {comment} the function {}:{}/{arity}?\n{{\nlet a = st.ops.op(instr.unwrap()).a({ap});\ndebug_assert!(a.ty == TAG_U);\nif a.ty != TAG_U {{ {fail}; }}\nlet i = a.val as usize;\ndebug_assert!(i < st.imports.len());\nif i >= st.imports.len() {{ {fail}; }}\nlet import = &st.imports[i];\nif import.module != {m} || import.function != {f} || import.arity != {arity} {{ {fail}; }}\n}}\n",
                    args[0], args[1]
                ));
            }
            "is_type" => out.push_str(&format!(
                "if ((1u32 << st.ops.op(instr.unwrap()).a({ap}).ty) & {}) == 0 {{ // {comment}\n    {fail};\n}}\n",
                args[0]
            )),
            "next_instr" => {
                let expected = &args[0];
                let window_check = if ip > 1 {
                    "if instr.is_none() { return TeResult::ShortWindow; }"
                } else {
                    "debug_assert!(instr.is_some());"
                };
                out.push_str(&format!(
                    "// Advance to next instruction\ninstr = st.ops.op(instr.unwrap()).next;\n{window_check}\nif st.ops.op(instr.unwrap()).op != {expected} {{ // {comment}\n    {fail};\n}}\n"
                ));
            }
            "call" => {
                let call = call_args(&args[1..]);
                out.push_str(&format!(
                    "// Call generator {0}()\n{{\nlet Some(new_instr) = generators::{0}(st{call}) else {{ {fail}; }};\nkeep = st.ops.op(instr.unwrap()).next; // The next_instr was optimized away.\nlet mut tail = new_instr;\nwhile let Some(next) = st.ops.op(tail).next {{ tail = next; }}\nst.ops.op_mut(tail).next = keep;\ninstr = Some(new_instr);\n}}\n",
                    args[0]
                ));
            }
            "pred" => {
                let call = call_args(&args[1..]);
                out.push_str(&format!(
                    "// Call predicate {0}()\nif !predicates::{0}(st{call}) {{\n    {fail};\n}}\n",
                    args[0]
                ));
            }
            "rest_args" => out.push_str(&format!(
                "// Store dynamic arguments ({comment})\nrest_args = RestArgs {{ op: instr.unwrap(), start: {0}, len: st.ops.op(instr.unwrap()).arity - {0} }};\nnum_rest_args = rest_args.len;\n",
                args[0]
            )),
            "commit" => out.push_str(&format!(
                "// {comment}\ninstr = st.ops.op(instr.unwrap()).next;\nkeep = instr;\n"
            )),
            "commit_new_instr" => {
                let op: usize = args[0].parse().unwrap();
                let arity = self.gen_arity[op];
                out.push_str(&format!(
                    "// {comment}; reusing last instruction on the left-hand side\ndebug_assert!(st.ops.op(instr.unwrap()).uses_def_args());\nkeep = instr;\n{{\nlet o = st.ops.op_mut(instr.unwrap());\no.op = {op};\no.arity = {arity};\n}}\n"
                ));
            }
            "keep" => out.push_str("// Keep the current instruction unchanged\nkeep = instr;\n"),
            "new_instr" => {
                let op: usize = args[0].parse().unwrap();
                let arity = self.gen_arity[op];
                out.push_str(&format!(
                    "// Create instruction: {comment}\n{{\nlet new_instr = st.ops.new_op();\nlet o = st.ops.op_mut(new_instr);\no.next = instr;\no.op = {op};\no.arity = {arity};\ninstr = Some(new_instr);\n}}\n"
                ));
            }
            "rename" => {
                let op: usize = args[0].parse().unwrap();
                let arity = self.gen_arity[op];
                out.push_str(&format!(
                    "// Rename instruction keeping the arguments\n{{\nlet o = st.ops.op_mut(instr.unwrap());\no.op = {op};\no.arity = {arity};\n}}\nreturn TeResult::Ok;\n"
                ));
            }
            "store_var" => out.push_str(&format!(
                "st.ops.op_mut(instr.unwrap()).set_a({ap}, v{}); // {comment}\n",
                args[0]
            )),
            "store_val" => out.push_str(&format!(
                "// Store value {comment}\nst.ops.op_mut(instr.unwrap()).set_a({ap}, BeamOpArg::new({}, {}));\n",
                args[0].to_uppercase(),
                args[1]
            )),
            "store_rest_args" => out.push_str(&format!(
                "// Store dynamic arguments ({comment})\ndebug_assert!(st.ops.op(instr.unwrap()).uses_def_args());\n{{\nlet o = st.ops.op_mut(instr.unwrap());\nlet arity = o.arity + num_rest_args;\no.spill(arity, {ap});\n}}\nfor k in 0..num_rest_args {{\nlet v = st.ops.op(rest_args.op).a(rest_args.start + k);\nst.ops.op_mut(instr.unwrap()).set_a({ap} + k, v);\n}}\n"
            )),
            "end" => out.push_str(
                "// End of transformation\nst.genop = instr;\nlet mut f = Some(first);\nwhile f != keep {\n    let id = f.expect(\"keep is on the chain\");\n    f = st.ops.op(id).next;\n    st.ops.free_op(id);\n}\nreturn TeResult::Ok;\n",
            ),
            "fail" => out.push_str("// Fail transformation\nreturn TeResult::Fail;\n"),
            other => panic!("Unhandled instruction: {other} {args:?}"),
        }
    }
}

/// An operand constant of the programs: a number or an `am_*` atom.
fn value_expr(text: &str, atoms: &mut BTreeSet<String>) -> String {
    match text.strip_prefix("am_") {
        Some(name) => {
            atoms.insert(name.to_owned());
            format!("AM_{}", name.to_uppercase())
        }
        None => text.to_owned(),
    }
}

fn call_args(args: &[String]) -> String {
    args.iter()
        .map(|a| {
            if a == "rest_args" {
                ", rest_args".to_owned()
            } else {
                format!(", {a}")
            }
        })
        .collect()
}

/// The text of a rule's `/* ... */` comment, without the comment decoration.
fn rule_comment(comment: &str) -> Vec<String> {
    comment
        .lines()
        .map(|l| {
            l.trim()
                .trim_start_matches("/*")
                .trim_start_matches("*/")
                .trim_start_matches('*')
                .trim()
                .to_owned()
        })
        .filter(|l| !l.is_empty())
        .collect()
}

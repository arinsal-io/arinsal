//! Atoms created by the `load` callbacks of the static NIF libraries.
//!
//! erts creates them with `enif_make_atom` (and resource type names in
//! `enif_open_resource_type`) when `erlang:load_nif/2` runs the callback; their
//! table indices decide flatmap key order and atom-key HAMT hashes.

/// Atoms the static NIF library of `module` creates while loading, in creation order.
pub(crate) fn load_atoms(module: &str) -> &'static [&'static str] {
    match module {
        "zlib" => ZLIB,
        "zstd" => ZSTD,
        "erl_tracer" => ERL_TRACER,
        "prim_buffer" => PRIM_BUFFER,
        "prim_file" => PRIM_FILE,
        "prim_tty" => PRIM_TTY,
        "prim_socket" => PRIM_SOCKET,
        "prim_net" => PRIM_NET,
        _ => &[],
    }
}


use arinsal_arith::{self as arith, ArithError};
use arinsal_term::{MAX_SMALL, ProcessHeap, Term, TermBuilder, VecHeap, to_owned};
use num_bigint::BigInt;

fn small(n: i64) -> Term {
    Term::small(n).unwrap()
}

#[test]
fn heap_full_is_atomic_and_reports_words() {
    let mut heap = ProcessHeap::with_words(0);
    assert_eq!(
        arith::add(small(MAX_SMALL), small(1), &mut heap),
        Err(ArithError::HeapFull { need_words: 2 })
    );
    assert_eq!(heap.used_words(), 0);
    assert_eq!(
        arith::integer_to_list(small(12345), small(10), &mut heap),
        Err(ArithError::HeapFull { need_words: 10 })
    );
    assert_eq!(heap.used_words(), 0);
    assert_eq!(
        arith::integer_to_binary(small(1), small(10), &mut heap),
        Err(ArithError::HeapFull { need_words: 3 })
    );
    assert_eq!(heap.used_words(), 0);
    assert_eq!(
        arith::fdiv(small(1), small(2), &mut heap),
        Err(ArithError::HeapFull { need_words: 2 })
    );
    assert_eq!(heap.used_words(), 0);
}

#[test]
fn large_shifts_saturate_or_raise() {
    let mut heap = VecHeap::new();
    let huge = TermBuilder::new(&mut heap)
        .int_from_bigint(&(BigInt::from(1u64) << 64usize))
        .unwrap();
    assert_eq!(
        arith::bsl(small(1), huge, &mut heap),
        Err(ArithError::SystemLimit)
    );
    assert_eq!(arith::bsr(small(1), huge, &mut heap), Ok(small(0)));
    assert_eq!(arith::bsr(small(-1), huge, &mut heap), Ok(small(-1)));
    assert_eq!(arith::bsl(small(0), huge, &mut heap), Ok(small(0)));
    let maximum = arith::bsl(small(1), small(4_194_239), &mut heap).unwrap();
    assert!(matches!(
        to_owned(maximum).unwrap(),
        arinsal_etf::OwnedTerm::BigInt(_)
    ));
    assert_eq!(
        arith::bsl(small(1), small(4_194_240), &mut heap),
        Err(ArithError::SystemLimit)
    );
}

#[test]
fn float_conversion_boundaries() {
    let mut heap = VecHeap::new();
    let n = TermBuilder::new(&mut heap)
        .int_from_bigint(&(BigInt::from(1u64) << 1024usize))
        .unwrap();
    assert_eq!(arith::to_float(n, &mut heap), Err(ArithError::Badarg));
    assert_eq!(
        arith::fdiv(n, small(2), &mut heap),
        Err(ArithError::Badarith)
    );
    let negative_zero = TermBuilder::new(&mut heap).float(-0.0).unwrap();
    let abs = arith::abs(negative_zero, &mut heap).unwrap();
    assert_eq!(format!("{:?}", to_owned(abs).unwrap()), "Float(0.0)");
}

#[test]
fn mixed_float_arithmetic_converts_integer_zero_like_otp() {
    let mut heap = VecHeap::new();
    let zero = small(0);
    let one = small(1);
    let negative_one = TermBuilder::new(&mut heap).float(-1.0).unwrap();

    let quotient = arith::fdiv(zero, one, &mut heap).unwrap();
    assert!(matches!(
        to_owned(quotient).unwrap(),
        arinsal_etf::OwnedTerm::Float(0.0)
    ));

    let product = arith::mul(negative_one, zero, &mut heap).unwrap();
    assert!(matches!(
        to_owned(product).unwrap(),
        arinsal_etf::OwnedTerm::Float(value) if value.to_bits() == (-0.0_f64).to_bits()
    ));
}

#[test]
fn bignum_float_conversion_rounds_like_otp() {
    // Expected f64 words generated by `erl` 29.1.1; this is the OTP-2436
    // regression set for ties-to-even conversion of multiword bignums.
    let cases = [
        (428654966685883400000_i128, 4_915_464_349_551_093_499),
        (38_409_289_721_754_710_000, 4_900_101_428_950_966_787),
        (34_784_104_853_086_640_000, 4_899_401_408_423_256_761),
        (385_269_108_828_434_300_000, 4_914_802_333_897_751_075),
        (96_874_578_115_970_900_000, 4_905_829_149_591_060_763),
        (252_558_769_001_389_900_000, 4_912_127_476_170_623_889),
        (26_465_126_867_694_860_000, 4_897_370_407_938_541_971),
    ];
    let mut heap = VecHeap::new();
    for (integer, expected_bits) in cases {
        let term = TermBuilder::new(&mut heap)
            .int_from_bigint(&BigInt::from(integer))
            .unwrap();
        let actual = arith::to_float(term, &mut heap).unwrap();
        let arinsal_etf::OwnedTerm::Float(actual) = to_owned(actual).unwrap() else {
            panic!("float/1 returned a non-float");
        };
        assert_eq!(actual.to_bits(), expected_bits, "float({integer})");
    }

    // OTP 29.1.1 rounds this value upward because its bit below the halfway
    // position is set; BigInt::to_f64 rounds it down on this wide-mantissa edge.
    let integer = ((BigInt::from(1_u8) << 52usize) << 76usize)
        + (BigInt::from(1_u8) << 75usize)
        + BigInt::from(1_u8);
    let term = TermBuilder::new(&mut heap)
        .int_from_bigint(&integer)
        .unwrap();
    let actual = arith::to_float(term, &mut heap).unwrap();
    let arinsal_etf::OwnedTerm::Float(actual) = to_owned(actual).unwrap() else {
        panic!("float/1 returned a non-float");
    };
    assert_eq!(actual.to_bits(), 5_183_643_171_103_440_897);
}
